"""Generate the footer wordmark (client/src/components/Footer/wordmark.js).

Extracts the real Instrument Serif glyph outlines for the photographer's name so
the footer can animate them being "written" (SVG strokes drawn, then inked).
The first letter is upright, the rest italic, plus an upright full stop, which
matches the original HTML wordmark.

Needs:  pip install fonttools
Fonts:  InstrumentSerif-Regular.ttf + InstrumentSerif-Italic.ttf (Google Fonts, OFL)

Usage:  python tools/wordmark.py <fonts-dir> [name]
        e.g. python tools/wordmark.py ~/Downloads/instrument-serif Arvin
"""

import json
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

LETTER_SPACING = -0.04  # em, same as .big-mark in Footer.css
OUT = Path(__file__).resolve().parent.parent / "client/src/components/Footer/wordmark.js"


def glyph(font, ch, x):
    """Path data for one character at pen position x (y flipped to SVG's y-down)."""
    gs = font.getGlyphSet()
    name = font.getBestCmap()[ord(ch)]
    g = gs[name]
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    g.draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
    bounds = BoundsPen(gs)
    g.draw(TransformPen(bounds, (1, 0, 0, -1, x, 0)))
    return pen.getCommands(), g.width, bounds.bounds


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    fonts = Path(sys.argv[1])
    name = sys.argv[2] if len(sys.argv) > 2 else "Arvin"
    upright = TTFont(fonts / "InstrumentSerif-Regular.ttf")
    italic = TTFont(fonts / "InstrumentSerif-Italic.ttf")
    upm = upright["head"].unitsPerEm

    chars = [(c, upright if i == 0 else italic, "ch" if i == 0 else "ch it") for i, c in enumerate(name)]
    chars.append((".", upright, "ch dot"))

    x = 0.0
    glyphs, xmin, ymin, xmax, ymax = [], 1e9, 1e9, -1e9, -1e9
    for ch, font, cls in chars:
        d, adv, (x0, y0, x1, y1) = glyph(font, ch, x)
        glyphs.append({"ch": ch, "cls": cls, "d": d})
        xmin, ymin, xmax, ymax = min(xmin, x0), min(ymin, y0), max(xmax, x1), max(ymax, y1)
        x += adv + LETTER_SPACING * upm

    pad = 0.02 * upm  # room for the outline stroke
    box = [round(xmin - pad), round(ymin - pad), round(xmax - xmin + 2 * pad), round(ymax - ymin + 2 * pad)]
    data = {"name": name, "upm": upm, "viewBox": box, "glyphs": glyphs}
    OUT.write_text(
        "// Generated by tools/wordmark.py from Instrument Serif (SIL Open Font License).\n"
        "// Do not edit by hand: re-run the script if the name changes.\n"
        f"export default {json.dumps(data, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(glyphs)} glyphs, viewBox {box})")


if __name__ == "__main__":
    main()
